"""Generate G1 and Cosmos paper macros from the scored results."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "transfergap" / "results"
OUT = Path(__file__).resolve().parent / "figures" / "new_results.tex"


def read(name):
    return json.loads((RESULTS / name / "summary.json").read_text())


def emit(name, value):
    return rf"\newcommand{{\{name}}}{{{value}}}"


def main():
    g1 = read("g1_contact_v1")["conditions"]
    v1 = read("cosmos_critic_v1")["results"]
    v2 = read("cosmos_critic_v2")["results"]
    assert v1["n"] == 120 and v2["n"] == 116 and v2["static_controls"]["n"] == 6
    lines = ["% AUTO-GENERATED by paper/new_result_numbers.py from scored result JSON -- do not edit."]
    for name, key in (("GOneNominal", "nominal_target"), ("GOneOracle", "true_target")):
        r = g1[key]
        assert r["rollouts"] == 30 and r["trials"] == 10
        for tier in ("touch", "grasp", "place"):
            lines.append(emit(name + tier.title() + "K", r[tier + "_rollout_rate"]["k"]))
        lines.append(emit(name + "N", r["rollouts"]))
        lines.append(emit(name + "PlaceSeedK", r["place_trial_any_rollout"]["k"]))
        lines.append(emit(name + "SeedN", r["trials"]))
    for name, r in (("CosmosOne", v1), ("CosmosTwo", v2)):
        lines.append(emit(name + "SuccessK", r["success"]["accuracy"]["correct"]))
        lines.append(emit(name + "SuccessN", r["n"]))
        lines.append(emit(name + "StageK", r["stage"]["accuracy"]["correct"]))
        lines.append(emit(name + "MajorityK", r["success"]["majority_baseline"]["correct"]))
    lines.append(emit("CosmosStaticN", v2["static_controls"]["n"]))
    lines.append(emit("CosmosStaticFalseK", v2["static_controls"]["said_success"]))
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
