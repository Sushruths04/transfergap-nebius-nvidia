"""Number macros for parts B-D of the paper, read ONLY from committed result files (no typing by hand).
Writes figures/real_numbers.tex and prints a check table (macro = value  <- source file).
  B real demos : results/demo_generalization_v5/summary.json, results/user_demo_v1/repro_summary.json
  C depth      : results/perception_hard_v1/heldout_scorecard.md, results/style_perception_v1/heldout_results.json
  D G1         : results/g1_style_v1/summary.json, results/g1_in_image_v1/summary.json and rows_*.json (grasp = lift >= 5 cm)
"""
import json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE.parent / "transfergap" / "results"
mac, log = {}, []

def put(name, val, src):
    mac[name] = str(val); log.append((name, str(val), src))

# ---- B: real demos
v5 = json.loads((R / "demo_generalization_v5/summary.json").read_text())["runs"]
CELL = {"A_pexels_8135753_notebook": "Notebook", "A_pexels_8135753_markers": "Markers", "A_pexels_8135753_orange_marker": "Orange",
        "A_pexels_8135753_notepad": "Notepad", "A_woman": "PTwoOwn", "B_woman": "PTwoPOne"}
for key, nm in CELL.items():
    for robot, rn in (("ur5e", "Five"), ("ur10e", "Ten")):
        c = v5[key][robot]
        put(f"dm{nm}{rn}Raw", c["raw"], f"demo_generalization_v5 {key} {robot} raw")
        put(f"dm{nm}{rn}Stack", c["stack"], f"demo_generalization_v5 {key} {robot} stack")
        assert c["gap"]["n"] == 60
        assert c["gap"]["ci95_pp"][0] > 0, f"{key} {robot}: gain CI includes zero"      # the table caption claims this
nb = v5["A_pexels_8135753_notebook"]
for robot, rn in (("ur5e", "Five"), ("ur10e", "Ten")):
    put(f"dmPathRaw{rn}", f"{100*nb[robot]['path_rmse_m']['raw']:.1f}", f"demo_generalization_v5 notebook {robot} path_rmse raw (cm)")
    put(f"dmPathFix{rn}", f"{100*nb[robot]['path_rmse_m']['all_fixes']:.1f}", f"demo_generalization_v5 notebook {robot} path_rmse all_fixes (cm)")
own = json.loads((R / "user_demo_v1/repro_summary.json").read_text())["robots"]
for robot, rn in (("ur5e", "Five"), ("ur10e", "Ten")):
    cc = own[robot]["conditions"]
    put(f"dmOwn{rn}Raw", cc["raw"]["successes"], f"user_demo_v1 {robot} raw")
    put(f"dmOwn{rn}Stack", cc["all_fixes"]["successes"], f"user_demo_v1 {robot} all_fixes")
    assert own[robot]["gap_all_fixes_minus_raw"]["ci95_pp"][0] > 0
allraw = [int(mac[f"dm{n}{r}Raw"]) for n in list(CELL.values()) + ["Own"] for r in ("Five", "Ten")]
allstk = [int(mac[f"dm{n}{r}Stack"]) for n in list(CELL.values()) + ["Own"] for r in ("Five", "Ten")]
put("dmRawMax", max(allraw), "max of raw cells"); put("dmStackMin", min(allstk), "min of stack cells")

v1 = json.loads((R / "demo_generalization_v1/summary.json").read_text())["demos"]
put("dmVOneDemos", len(v1), "demo_generalization_v1 demos")
put("dmVOneMax", max(r["all_fixes"][0] for d in v1.values() for r in d["robots"].values()), "v1: max successes of the unchanged notebook stack over demos and arms")
v4 = json.loads((R / "demo_generalization_v4/summary.json").read_text())["robots"]
put("dmVFourRaw", v4["ur5e"]["raw"], "demo_generalization_v4 ur5e raw"); put("dmVFourStack", v4["ur5e"]["all_fixes"], "demo_generalization_v4 ur5e stack")

cost = [100 * (v5["A_" + d][rob]["path_rmse_m"]["all_fixes"] - x["path_rmse_m"]["all_fixes"]) for d, r in v1.items() for rob, x in r["robots"].items()]
put("dmCostMin", f"{min(cost):.1f}", "path-RMSE cost of safe_path_v2: v5 stack minus v1 stack, same demo and arm (cm), min of 6 cells")
put("dmCostMax", f"{max(cost):.1f}", "same, max of 6 cells")

# ---- C: depth perception (scorecard markdown generated by the repo from the held-out episodes)
sc = (R / "perception_hard_v1/heldout_scorecard.md").read_text()
rows = {}
for line in sc.splitlines():
    m = re.match(r"\| (\*?)(\w+) \| (.*) \|$", line)
    if m and m.group(2) not in ("condition",):
        cells = [re.match(r"(\d+)/(\d+)", c.strip()) for c in m.group(3).split(" | ")]
        if all(cells):
            rows[m.group(2)] = (bool(m.group(1)), [int(c.group(1)) for c in cells], int(cells[0].group(2)))
bars = {k: v for k, v in rows.items() if v[0]}
n_cells = sum(len(v[1]) for v in bars.values()); met = sum(k_ >= 0.9 * v[2] for v in bars.values() for k_ in v[1])
put("pcBarCells", n_cells, "scorecard: starred conditions x 3 robots"); put("pcBarMet", met, "cells with >= 0.90 pooled success")
put("pcBarMin", min(k_ for v in bars.values() for k_ in v[1]), "min successes among bar cells"); put("pcN", rows["truth_yaw_aware"][2], "episodes per cell")
put("pcYawBlindFive", rows["truth_yaw_blind"][1][0], "truth_yaw_blind ur5e"); put("pcYawBlindTen", rows["truth_yaw_blind"][1][1], "truth_yaw_blind ur10e")
put("pcCalibTwoFive", rows["depth_calib_2deg_20mm"][1][0], "depth_calib_2deg_20mm ur5e")
arm = [k_ for n in ("depth_arm_side", "depth_arm_over") for k_ in rows[n][1]]
put("pcArmMin", min(arm), "arm in view, no retry: min over robots"); put("pcArmMax", max(arm), "arm in view, no retry: max over robots")
sp = json.loads((R / "style_perception_v1/heldout_results.json").read_text())["summary"]
for robot, rn in (("ur5e", "Five"), ("ur10e", "Ten"), ("kairos", "Kai")):
    for belief, bn in (("truth", "Truth"), ("depth", "Depth"), ("depth_hard", "Hard")):
        put(f"spK{rn}{bn}", sum(v["success"] for k, v in sp.items() if k.startswith(f"{robot}/{belief}/")), f"style_perception_v1 {robot} {belief} (sum over 3 sizes)")
put("spN", sum(v["n"] for k, v in sp.items() if k.startswith("ur5e/truth/")), "style_perception_v1 episodes per cell")

# ---- D: G1
gs = json.loads((R / "g1_style_v1/summary.json").read_text())["conditions"]
for key, nm in (("style_human_pace", "Human"), ("style_speed_cap_3", "Cap"), ("style_nominal_pace", "Nominal")):
    c = gs[key]
    for lvl, ln in (("touch", "Touch"), ("grasp", "Grasp"), ("place", "Place")):
        put(f"gs{nm}{ln}", c[f"{lvl}_rollout_rate"]["k"], f"g1_style_v1 {key} {lvl}")
    put(f"gs{nm}N", c["grasp_rollout_rate"]["n"], f"g1_style_v1 {key} rollouts")
gx = json.loads((R / "g1_style_in_image_v1/summary.json").read_text())["conditions"]
for key, nm in (("style_human_pace", "Human"), ("style_speed_cap_3", "Cap"), ("style_nominal_pace", "Nominal")):
    for lvl, ln in (("touch", "Touch"), ("grasp", "Grasp"), ("place", "Place")):
        put(f"gx{nm}{ln}", gx[key][f"{lvl}_rollout_rate"]["k"], f"g1_style_in_image_v1 {key} {lvl}")
gi = json.loads((R / "g1_in_image_v1/summary.json").read_text())
for k, nm in (("touch_in_image", "ImgTouch"), ("grasp_in_image", "ImgGrasp"), ("place_in_image", "ImgPlace"),
              ("touch_host", "HostTouch"), ("grasp_host", "HostGrasp"), ("place_host", "HostPlace"), ("place_only_in_image", "OnlyImg"), ("place_only_host", "OnlyHost"), ("n", "N")):
    put(f"gi{nm}", gi[k], f"g1_in_image_v1/summary.json {k}")
put("giP", f"{gi['place_mcnemar_exact_two_sided']:.1e}".replace("e-0", "e-").replace("e-", r"\times 10^{-") + "}", "place McNemar exact two-sided")
D = R / "g1_in_image_v1"
def grasps(f, lo=1200, hi=1209):
    rows_ = json.loads((D / f).read_text()); rows_ = [r for r in rows_ if lo <= r["seed"] <= hi]
    assert len(rows_) == 10, f; return sum(r["lift_cm"] >= 5 for r in rows_)
host_files = ["rows_host_fresh_pod_1200_1209.json", "rows_host_no_cached_engine_1200_1209.json", "rows_host_sameday_v2_1200_1209.json", "rows_host_sameday_v3_1200_1209.json"]
img_files = ["rows_image_hostlike_cpu_1200_1209.json", "rows_image_deployment_pod_1200_1209.json", "rows_image_hostlike_cuda_libs_1200_1209.json", "rows_image_host_binaries_1200_1209.json"]
orig = [r for r in json.loads((R / "g1_pelvis_drift_v1/rows.json").read_text()) if 1200 <= r["seed"] <= 1209]
assert len(orig) == 10
host = [sum(r["lift_cm"] >= 5 for r in orig)] + [grasps(f) for f in host_files]       # original pelvis-drift run first
img = [grasps(f) for f in img_files]
first = [r for f in ("rows_seeds_1200_1202.json", "rows_seeds_1203_1239.json") for r in json.loads((D / f).read_text()) if 1200 <= r["seed"] <= 1209]
assert len(first) == 10; img.append(sum(r["lift_cm"] >= 5 for r in first))
hostorig = [r for r in gi.get("rows_host", [])] if "rows_host" in gi else None
log.append(("host runs (original, fresh pod, no cache, sameday v2, v3)", str(host), "rows_host_*.json"))
log.append(("image variants (hostlike cpu, deployment, cuda libs, host binaries, first jobs)", str(img), "rows_image_*.json + rows_seeds_*.json"))
put("gRerunHostK", sum(host), "sum of the five host runs of seeds 1200-1209 (g1_pelvis_drift_v1 + rows_host_*)")
put("gRerunHostN", 10 * len(host), "")
put("gRerunImgK", sum(img), "sum of image variants"); put("gRerunImgN", 10 * len(img), "")
put("gRerunHostMin", min(host), ""); put("gRerunHostMax", max(host), "")

mj = {v: json.loads((D / ".." / "g1_mujoco_version_v1" / f"rows_mujoco_{v}.json").read_text()) for v in ("3_14_0", "3_15_0")}
for v, nm in (("3_14_0", "Old"), ("3_15_0", "New")):
    put(f"mjGrasp{nm}", sum(r["lift_cm"] >= 5 for r in mj[v]), f"g1_mujoco_version_v1 mujoco {v} grasps (lift >= 5 cm)")
    put(f"mjN{nm}", len(mj[v]), f"g1_mujoco_version_v1 mujoco {v} seeds")

(HERE / "figures" / "real_numbers.tex").write_text("".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items()))
w = max(len(k) for k, _, _ in log)
for k, v, s in log: print(f"{k:<{w}} = {v:<28} <- {s}")
